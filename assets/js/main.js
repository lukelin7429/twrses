/* 人師教育協會 twrses.org — interactions */
(function () {
  'use strict';

  /* mobile nav toggle */
  var toggle = document.querySelector('.nav-toggle');
  var menu = document.querySelector('.menu');
  if (toggle && menu) {
    toggle.addEventListener('click', function () {
      menu.classList.toggle('open');
      toggle.classList.toggle('on');
      var open = menu.classList.contains('open');
      toggle.setAttribute('aria-expanded', open ? 'true' : 'false');
    });
    menu.querySelectorAll('a').forEach(function (a) {
      a.addEventListener('click', function () {
        if (!a.parentElement.classList.contains('has-sub')) menu.classList.remove('open');
      });
    });
  }

  /* scroll reveal — getBoundingClientRect 版（不用 IntersectionObserver）
     原本用 IO + threshold 0.14：比視窗高 ~7 倍的元素（如 100 張卡的網格）露出面積永遠到不了 14%，
     導致整批內容卡在 opacity:0 → 整頁空白。改用 gBCR：元素上緣進入視窗就揭示，與高度無關。 */
  /* 全站自動揭示：對每個區段的內容區塊加 .ar，讓捲動時都有淡入動感（跳過 hero 與已手動標記者） */
  [].forEach.call(document.querySelectorAll('main section > .wrap > *'), function (el) {
    if (el.closest('.hero')) return;
    if (el.classList.contains('rvl') || el.classList.contains('stagger') ||
        el.classList.contains('ar') || el.classList.contains('sweep')) return;
    var p = el.parentNode;
    p.__arN = (p.__arN || 0);
    el.style.transitionDelay = (Math.min(p.__arN, 5) * 0.07) + 's';
    p.__arN++;
    el.classList.add('ar');
  });

  var revealEls = [].slice.call(document.querySelectorAll('.rvl, .stagger, .sweep, .ar'));
  if (revealEls.length) {
    var revealScan = function () {
      var vh = window.innerHeight || document.documentElement.clientHeight;
      for (var i = revealEls.length - 1; i >= 0; i--) {
        var r = revealEls[i].getBoundingClientRect();
        if (r.top < vh * 0.92 && r.bottom > 0) {   // 上緣進入視窗下 92% 且未完全捲離 → 揭示
          revealEls[i].classList.add('in');
          revealEls.splice(i, 1);
        }
      }
    };
    revealScan();
    window.addEventListener('scroll', revealScan, { passive: true });
    window.addEventListener('resize', revealScan, { passive: true });
    window.addEventListener('load', revealScan);
  }

  /* click-to-play: play the video INLINE in its own card — no lightbox, never pop out to YouTube */
  document.addEventListener('click', function (ev) {
    var card = ev.target.closest('[data-yt]');
    if (!card) return;
    ev.preventDefault();                    // hard-block any navigation to YouTube
    if (card.classList.contains('playing')) return;
    var stage = card.querySelector('.vthumb') || card;
    var id = card.getAttribute('data-yt');
    var title = (card.getAttribute('title') || '影片').replace(/"/g, '&quot;');
    stage.innerHTML =
      '<iframe src="https://www.youtube.com/embed/' + id +
      '?autoplay=1&rel=0&modestbranding=1&playsinline=1" title="' + title + '" ' +
      'allow="autoplay; encrypted-media; picture-in-picture; fullscreen" allowfullscreen ' +
      'style="position:absolute;inset:0;width:100%;height:100%;border:0;display:block"></iframe>';
    card.classList.add('playing');
  });

  /* 期刊就地翻頁閱讀器 */
  (function () {
    var reader = document.getElementById('periReader');
    if (!reader) return;
    var img = reader.querySelector('.pr-img'),
        curEl = reader.querySelector('.pr-cur'),
        totEl = reader.querySelector('.pr-total');
    var base = '', total = 1, cur = 1;
    function show(n) { if (n < 1) n = total; if (n > total) n = 1; cur = n; img.src = base + n + '.jpg'; curEl.textContent = n; }
    document.addEventListener('click', function (e) {
      var cover = e.target.closest('.peri-cover[data-read]');
      if (cover) {
        e.preventDefault();
        base = cover.getAttribute('data-read'); total = +cover.getAttribute('data-pages');
        reader.querySelector('.pr-title').textContent = cover.getAttribute('data-title');
        reader.querySelector('.pr-dl').href = cover.getAttribute('data-pdf');
        totEl.textContent = total;
        var card = cover.closest('.peri-card');
        card.parentNode.insertBefore(reader, card.nextSibling);   // 全寬列插在該卡之後
        reader.hidden = false; show(1);
        reader.scrollIntoView({ behavior: 'smooth', block: 'center' });
        return;
      }
      var b = e.target.closest('.pr-prev, .pr-next, .pr-close');
      if (b) {
        if (b.classList.contains('pr-close')) { reader.hidden = true; img.src = ''; }
        else show(cur + (b.classList.contains('pr-next') ? 1 : -1));
      }
    });
    document.addEventListener('keydown', function (e) {
      if (reader.hidden) return;
      if (e.key === 'ArrowLeft') show(cur - 1);
      else if (e.key === 'ArrowRight') show(cur + 1);
      else if (e.key === 'Escape') { reader.hidden = true; img.src = ''; }
    });
  })();

  /* 🔊 buttons — a recorded clip where we have one, the device voice otherwise.
     The clips are generated by tools/gen_audio.py (Azure en-US neural voice) and
     served from a GitHub release; the manifest maps a phrase to its filename.
     The device voice is whatever the visitor's OS ships — fine on a Mac, poor on
     Windows, often absent on Android — so it is the fallback, not the default.
     Note this is only for words, example sentences and questions: the passages
     themselves are read by a human and play from their own <audio> players. */
  var SAY_BASE = 'https://github.com/lukelin7429/twrses/releases/download/booklet-say-audio/';
  var sayManifest = null;
  var sayAudio = null;

  (function loadSayManifest() {
    var slug = document.body && document.body.getAttribute('data-say-manifest');
    if (!slug) return;
    fetch('/assets/data/say/' + slug + '.json')
      .then(function (r) { return r.ok ? r.json() : null; })
      .then(function (m) { if (m) sayManifest = m; })
      .catch(function () { /* fallback voice still works */ });
  })();

  var enVoice = null;
  function pickVoice() {
    var vs = window.speechSynthesis ? speechSynthesis.getVoices() : [];
    enVoice = vs.find(function (v) { return /en[-_]US/i.test(v.lang) && /female|samantha|google/i.test(v.name); })
           || vs.find(function (v) { return /^en/i.test(v.lang); }) || null;
  }
  if (window.speechSynthesis) {
    pickVoice();
    speechSynthesis.onvoiceschanged = pickVoice;
  }

  function sayFallback(text, btn) {
    if (!window.speechSynthesis) { if (btn) btn.classList.remove('on'); return; }
    speechSynthesis.cancel();
    var u = new SpeechSynthesisUtterance(text);
    u.lang = 'en-US'; u.rate = 0.92; if (enVoice) u.voice = enVoice;
    if (btn) { btn.classList.add('on'); u.onend = u.onerror = function () { btn.classList.remove('on'); }; }
    speechSynthesis.speak(u);
  }

  window.say = function (text, btn) {
    if (!text) return;
    if (sayAudio) { sayAudio.pause(); sayAudio = null; }
    if (window.speechSynthesis) speechSynthesis.cancel();
    document.querySelectorAll('[data-say].on').forEach(function (b) { b.classList.remove('on'); });

    var hash = sayManifest && sayManifest[text];
    if (!hash) { sayFallback(text, btn); return; }

    var a = new Audio(SAY_BASE + hash + '.mp3');
    sayAudio = a;
    if (btn) btn.classList.add('on');
    var done = false;
    function fail() {
      if (done) return;
      done = true; sayAudio = null;
      if (btn) btn.classList.remove('on');
      sayFallback(text, btn);
    }
    a.onended = function () { done = true; sayAudio = null; if (btn) btn.classList.remove('on'); };
    a.onerror = fail;
    var p = a.play();
    if (p && p.catch) p.catch(fail);
  };
  document.addEventListener('click', function (e) {
    var b = e.target.closest('[data-say]');
    if (b) { e.preventDefault(); window.say(b.getAttribute('data-say'), b); }
    var t = e.target.closest('.tr-toggle');
    if (t) {
      var box = document.getElementById(t.getAttribute('data-target'));
      if (box) {
        box.classList.toggle('show');
        var open = box.classList.contains('show');
        t.textContent = open ? (t.getAttribute('data-hide') || '隱藏中文翻譯') : (t.getAttribute('data-show') || '顯示中文翻譯');
      }
    }
    var lec = e.target.closest('.lec-btn');
    if (lec) {
      e.preventDefault();
      var wrap = lec.closest('.lecture');
      var stage = wrap.querySelector('.lec-stage');
      var icon = lec.querySelector('.lec-play');
      if (wrap.classList.contains('playing')) {        // toggle off → stop
        stage.innerHTML = ''; wrap.classList.remove('playing'); if (icon) icon.textContent = '▶';
      } else {
        document.querySelectorAll('.lecture.playing').forEach(function (o) {  // only one at a time
          o.querySelector('.lec-stage').innerHTML = ''; o.classList.remove('playing');
          var oi = o.querySelector('.lec-play'); if (oi) oi.textContent = '▶';
        });
        var id = lec.getAttribute('data-ytin');
        var tEl = lec.querySelector('.lec-t');
        var ttl = (tEl ? tEl.textContent : '講解').replace(/"/g, '&quot;');
        stage.innerHTML = '<iframe src="https://www.youtube.com/embed/' + id +
          '?autoplay=1&rel=0&modestbranding=1&playsinline=1" title="' + ttl +
          '" allow="autoplay; encrypted-media; picture-in-picture" allowfullscreen></iframe>';
        wrap.classList.add('playing'); if (icon) icon.textContent = '❚❚';
      }
    }
    var q = e.target.closest('.quiz-opt');
    if (q && !q.parentElement.classList.contains('done')) {
      var correct = q.getAttribute('data-correct') === '1';
      q.parentElement.classList.add('done');
      q.classList.add(correct ? 'right' : 'wrong');
      if (!correct) { var r = q.parentElement.querySelector('[data-correct="1"]'); if (r) r.classList.add('right'); }
    }
  });

  /* carousel */
  document.querySelectorAll('[data-carousel]').forEach(function (car) {
    var track = car.querySelector('.car-track');
    var slides = car.querySelectorAll('.car-slide');
    var dots = car.querySelectorAll('.car-dot');
    var n = slides.length, i = 0, timer;
    function go(k) {
      i = (k + n) % n;
      track.style.transform = 'translateX(' + (-i * 100) + '%)';
      dots.forEach(function (d, j) { d.classList.toggle('on', j === i); });
    }
    function play() { stop(); timer = setInterval(function () { go(i + 1); }, 5000); }
    function stop() { if (timer) clearInterval(timer); }
    var prev = car.querySelector('.car-prev'), next = car.querySelector('.car-next');
    if (prev) prev.addEventListener('click', function () { go(i - 1); play(); });
    if (next) next.addEventListener('click', function () { go(i + 1); play(); });
    dots.forEach(function (d) { d.addEventListener('click', function () { go(+d.getAttribute('data-i')); play(); }); });
    car.addEventListener('mouseenter', stop);
    car.addEventListener('mouseleave', play);
    if (n > 1) play();
  });

  /* header shadow on scroll */
  var header = document.querySelector('.site-header');
  if (header) {
    var onScroll = function () {
      if (window.scrollY > 12) header.style.boxShadow = '0 10px 30px -22px rgba(22,48,44,.5)';
      else header.style.boxShadow = 'none';
    };
    window.addEventListener('scroll', onScroll, { passive: true });
    onScroll();
  }

  /* sticky unit-nav: highlight the unit currently in view and keep its chip in the track */
  var unav = document.querySelector('.unit-nav');
  if (unav) {
    var navTrack = unav.querySelector('.unit-nav-track');
    var navLinks = [].slice.call(unav.querySelectorAll('.unit-nav-link'));
    var navTargets = navLinks.map(function (a) { return document.getElementById(a.getAttribute('href').slice(1)); });
    var navLast = -1;
    var syncNav = function () {
      var offset = unav.getBoundingClientRect().bottom + 8;
      var idx = 0;
      for (var k = 0; k < navTargets.length; k++) {
        if (navTargets[k] && navTargets[k].getBoundingClientRect().top <= offset) idx = k;
      }
      if (idx === navLast) return;
      navLast = idx;
      navLinks.forEach(function (a, j) { a.classList.toggle('active', j === idx); });
      var cur = navLinks[idx];
      if (navTrack && cur) navTrack.scrollTo({ left: cur.offsetLeft - navTrack.clientWidth / 2 + cur.offsetWidth / 2, behavior: 'smooth' });
    };
    window.addEventListener('scroll', syncNav, { passive: true });
    syncNav();
  }
})();

/* 專文展開／收合 */
(function () {
  var btn = document.getElementById('essayBtn'), rest = document.getElementById('essayRest');
  if (!btn || !rest) return;
  btn.addEventListener('click', function () {
    var open = rest.hasAttribute('hidden');
    if (open) rest.removeAttribute('hidden'); else rest.setAttribute('hidden', '');
    btn.setAttribute('aria-expanded', open);
    btn.textContent = open ? '收合全文 ↑' : '閱讀全文 ↓';
    if (!open) btn.scrollIntoView({ block: 'center', behavior: 'smooth' });
  });
})();

/* 照片燈箱：點縮圖看原圖，← → 切換，ESC／點背景／× 關閉 */
(function () {
  var links = [].slice.call(document.querySelectorAll('.pgallery a[data-lb]'));
  var lb = document.getElementById('lb');
  if (!links.length || !lb) return;
  var img = lb.querySelector('.lb-img'), cap = lb.querySelector('.lb-c'), i = 0;
  function show(n) {
    i = (n + links.length) % links.length;
    img.src = links[i].getAttribute('href');
    img.alt = links[i].querySelector('img').alt || '';
    cap.textContent = (i + 1) + ' / ' + links.length;
    lb.removeAttribute('hidden');
    document.body.style.overflow = 'hidden';
  }
  function hide() { lb.setAttribute('hidden', ''); img.src = ''; document.body.style.overflow = ''; }
  links.forEach(function (a, n) {
    a.addEventListener('click', function (e) { e.preventDefault(); show(n); });
  });
  lb.querySelector('.lb-x').addEventListener('click', hide);
  lb.querySelector('.lb-p').addEventListener('click', function (e) { e.stopPropagation(); show(i - 1); });
  lb.querySelector('.lb-n').addEventListener('click', function (e) { e.stopPropagation(); show(i + 1); });
  lb.addEventListener('click', function (e) { if (e.target === lb || e.target === img) hide(); });
  document.addEventListener('keydown', function (e) {
    if (lb.hasAttribute('hidden')) return;
    if (e.key === 'Escape') hide();
    if (e.key === 'ArrowLeft') show(i - 1);
    if (e.key === 'ArrowRight') show(i + 1);
  });
})();
