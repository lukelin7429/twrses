// 懸日：從氣象署公布的 5 月時段中點反推街道方位，預測 8 月與另一條街——
const taipei = { lat: 25.04, lon: 121.51, tz: 8 };
const roadOf = (iso) => sunAltAzOf(new Date(iso), taipei).az;
const runs = (az) => groupRuns(hengeDays(az, taipei, 2026)).map(([a, b]) => `${a.m}/${a.d}-${b.m}/${b.d}`);
const zx = roadOf('2026-05-01T18:03:00+08:00'), em = roadOf('2026-05-04T18:05:00+08:00');
console.log(`Taipei henge 2026: Zhongxiao Rd (az ${zx.toFixed(1)}°) ${runs(zx).join(', ')}; Emei St (az ${em.toFixed(1)}°) ${runs(em).join(', ')}`);
assert.deepEqual(runs(zx), ['4/30-5/2', '8/10-8/12']);
assert.deepEqual(runs(em), ['5/3-5/5', '8/7-8/9']);

// 陶寺（示意）：13 根柱子、12 道縫，第 2 道縫對冬至日出、第 12 道對夏至日出、第 7 道在春秋分附近
const taosi = { lat: 35.88, lon: 111.5, tz: 8 };
