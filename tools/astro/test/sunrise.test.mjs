assert.equal(slotOf(tex.south.riseAz), 2); assert.equal(slotOf(tex.north.riseAz), 12);
const tve = sunDay({ y: 2026, m: 3, d: 20 }, taosi);
assert.equal(slotOf(tve.riseAz), 7);
