const changhua = { lat: 24.08, lon: 120.54, tz: 8 };
const yr = sunYear(2026, changhua);
const tw = (d) => { const x = new Date(d.getTime() + 8 * 3600000); return x.getUTCHours() * 60 + x.getUTCMinutes() + x.getUTCSeconds() / 60; };
const hm = (s) => +s.slice(0, 2) * 60 + +s.slice(2);
let worst = { rise: 0, set: 0, raz: 0, saz: 0 };
for (const row of CWA) {
  const [md, rise, raz, set, saz] = row.split(' ');
  const x = yr.find((q) => q.m === +md.slice(0, 2) && q.d === +md.slice(2));
  const e = { rise: Math.round(tw(x.rise)) - hm(rise), set: Math.round(tw(x.set)) - hm(set), raz: x.riseAz - +raz, saz: x.setAz - +saz };
  for (const k in e) worst[k] = Math.max(worst[k], Math.abs(e[k]));
}
console.log(`Changhua 2026 vs CWA (${CWA.length} days): worst sunrise ${worst.rise} min, sunset ${worst.set} min, sunrise az ${worst.raz.toFixed(2)}°, sunset az ${worst.saz.toFixed(2)}°`);
assert.equal(CWA.length, 360);
assert.ok(worst.rise <= 1 && worst.set <= 1);
assert.ok(worst.raz < 1 && worst.saz < 1);

// 一年的擺盪：彰化日出最北在夏至（東偏北約 26°）、最南在冬至（東偏南約 25°），正東在春分秋分前後
const ex = sunriseExtremes(yr);
console.log(`Changhua: northmost ${ex.north.m}/${ex.north.d} az ${ex.north.riseAz.toFixed(1)}°, southmost ${ex.south.m}/${ex.south.d} az ${ex.south.riseAz.toFixed(1)}°, swing ${ex.swing.toFixed(1)}°; due east ${ex.dueEast.map((x) => `${x.m}/${x.d}`).join(', ')}`);
assert.ok(ex.north.m === 6 && Math.abs(ex.north.d - 21) <= 3 && Math.abs(ex.north.riseAz - 64) < 1);
assert.ok(ex.south.m === 12 && Math.abs(ex.south.d - 21) <= 3 && Math.abs(ex.south.riseAz - 115.4) < 1);
assert.ok(ex.swing > 50 && ex.swing < 53);
assert.deepEqual(ex.dueEast.map((x) => `${x.m}/${x.d}`), ['3/20', '9/24']);
// 春分那天日出方位略偏北（< 0.5°）：大氣折射讓太陽提早露臉，那時它還在地平線下、偏北一點的位置
const ve = yr.find((x) => x.m === 3 && x.d === 20);
assert.ok(ve.riseAz < 90.5);
// 日出點在春秋分移得最快（每天約 0.4°，快一個太陽寬），在冬夏至幾乎不動
const shift = (m, d) => { const k = yr.findIndex((x) => x.m === m && x.d === d); return Math.abs(yr[k].riseAz - yr[k - 1].riseAz); };
console.log(`Daily shift: Mar 20 ${shift(3, 20).toFixed(2)}°, Jun 21 ${shift(6, 21).toFixed(3)}°, Sep 23 ${shift(9, 23).toFixed(2)}°, Dec 22 ${shift(12, 22).toFixed(3)}°`);
assert.ok(shift(3, 20) > 0.38 && shift(9, 23) > 0.38);
assert.ok(shift(6, 21) < 0.03 && shift(12, 22) < 0.03);
// 解析公式（赤緯 ±23.44°）與逐日計算一致
assert.ok(Math.abs(riseAzimuth(23.44, 24.08) - ex.north.riseAz) < 0.3);
assert.ok(Math.abs(riseAzimuth(-23.44, 24.08) - ex.south.riseAz) < 0.3);
// 緯度越高擺得越寬：赤道約 ±23.5°、彰化約 ±26°、陶寺約 ±29°、巨石陣約 ±39°
const swing = (lat) => riseAzimuth(-23.44, lat) - riseAzimuth(23.44, lat);
console.log(`Swing: equator ${swing(0).toFixed(1)}°, Changhua ${swing(24.08).toFixed(1)}°, Taosi ${swing(35.88).toFixed(1)}°, Stonehenge ${swing(51.18).toFixed(1)}°`);
assert.ok(Math.abs(swing(0) - 46.9) < 0.3 && swing(35.88) > 58 && swing(35.88) < 60.5 && swing(51.18) > 78);

